"""Page 5: reports written by the Reporting Agent (view, download, generate) and evidence validation."""
from __future__ import annotations

import streamlit as st

from sentinelai.dashboard import theme
from sentinelai.dashboard.client import ApiError
from sentinelai.dashboard.views.common import client, fetch, system


def _for_display(markdown: str) -> str:
    """Keep the report's line structure when rendered (display only; the file is not changed).

    Standard Markdown joins consecutive lines into one paragraph, which merges the
    report's header fields. A hard line break is added between such lines."""
    lines = markdown.split("\n")
    out = []
    for line, nxt in zip(lines, lines[1:] + [""]):
        plain = line.strip() and nxt.strip() and not line.lstrip().startswith(("#", "-", "*  ", "|")) \
            and not nxt.lstrip().startswith(("-", "#"))
        out.append(line + "  " if plain else line)
    return "\n".join(out)


def _validation_panel(v: dict) -> None:
    theme.section("Evidence validation (EvidenceValidator, run now)")
    c1, c2 = st.columns([2, 3])
    with c1:
        theme.kv([
            ("Stored messages", theme.badge("passed", "#22C55E") if v["valid"]
             else theme.badge("failed", "#EF4444")),
            ("Messages checked", theme.esc(v["messages_checked"])),
            ("Scope", theme.esc(v["scope"])),
            ("Flow references", theme.badge(f"checked ({v['flow_ids_available']} flow IDs)", "#22C55E")
             if v["flow_references_checked"] else theme.badge("not checked: no flow file", "#64748B")),
            ("Rule definitions", theme.badge("not verified", "#94A3B8")),
        ], raw=True)
        if v["errors"]:
            st.markdown("**Problems found**")
            for e in v["errors"]:
                theme.html_block(f"<div class='sx-rec' style='border-color:#EF444488'>{theme.esc(e)}</div>")
    with c2:
        st.markdown("**Limitations**")
        for text in v["limitations"]:
            theme.html_block(f"<div class='sx-muted'>• {theme.esc(text)}</div>")


def _generate(sys_info: dict, reports: list[dict]) -> None:
    current = fetch("/api/assessments", current_only="true")["items"]
    reported = {r["assessment_id"] for r in reports if r["generated"]}
    with st.expander("Generate a report with the Reporting Agent", expanded=not reports):
        if not current:
            st.caption("No assessment of a latest incident version is stored.")
            return
        labels = {a["message_id"]: f"{a['message_id']} · {a['incident_id']} v{a['incident_version']} · "
                                   f"{a['severity']}" + (" · report exists" if a["message_id"] in reported else "")
                  for a in current}
        pick = st.selectbox("Assessment", list(labels), format_func=labels.get, key="rep-gen-pick")
        st.caption("Reuses the stored ReportRequest for this assessment if there is one; otherwise records a new "
                   "ReportRequest from the analyst. The Reporting Agent refuses if evidence validation fails.")
        if st.button("Generate report", type="primary"):
            try:
                _, report = client().post("/api/reports", {"assessment_id": pick})
                st.session_state["report_id"] = report["request_id"]
                st.session_state["rep-flash"] = f"Report {report['request_id']} generated by the Reporting Agent."
                st.rerun()
            except ApiError as exc:
                theme.banner(f"Report not generated: {exc.detail}", "error")


def render() -> None:
    sys_info = system()
    theme.header("Incident Reports", "Markdown reports written by the Reporting Agent (L-4).")
    theme.demo_banner(sys_info)
    if flash := st.session_state.pop("rep-flash", None):
        st.success(flash)

    reports = fetch("/api/reports")["items"]
    _generate(sys_info, reports)

    if not reports:
        theme.empty("No report requests stored yet.")
        _validation_panel(fetch("/api/validation"))
        return

    ids = [r["request_id"] for r in reports]
    labels = {r["request_id"]: f"{r['request_id']} · {r['incident_id']} · {r['severity'] or '?'}"
                               + ("" if r["generated"] else " · not generated") for r in reports}
    if st.session_state.get("report_id") not in ids:
        st.session_state["report_id"] = next((r["request_id"] for r in reports if r["generated"]), ids[0])
    request_id = st.selectbox("Report", ids, key="report_id", format_func=labels.get)
    report = fetch(f"/api/reports/{request_id}")

    c1, c2 = st.columns([3, 1.2])
    with c1:
        theme.html_block(
            theme.severity_badge(report["severity"])
            + theme.badge(f"Incident {report['incident_id']}", "#818CF8")
            + theme.badge(f"Assessment {report['assessment_id']} (v{report['assessment_incident_version']})", "#38BDF8")
            + (theme.badge("Demo fixtures", "#FBBF24") if report["is_demo_data"] else theme.badge("Agent output", "#94A3B8"))
            + ("" if report["is_current"] else theme.badge("Older incident version", "#F97316"))
        )
        st.caption(f"Requested {theme.fmt_ts(report['requested_at'])} by {report['requested_by']} "
                   f"({report['reason']}) · generated {theme.fmt_ts(report['generated_at']) or 'not yet'}")
    with c2:
        if report["generated"]:
            try:
                data = client().download(f"/api/reports/{request_id}/download")
                st.download_button("Download Markdown", data=data, file_name=f"{request_id}.md",
                                   mime="text/markdown", type="primary")
            except ApiError as exc:
                theme.banner(f"Download unavailable: {exc.detail}", "error")

    if report["content"]:
        with st.container(border=True, height=640, key="report-view"):
            # Markdown only: raw HTML inside report text is not rendered.
            st.markdown(_for_display(report["content"]))
    else:
        theme.empty("This report has not been generated yet. Use \"Generate a report\" above.")

    _validation_panel(fetch("/api/validation"))
